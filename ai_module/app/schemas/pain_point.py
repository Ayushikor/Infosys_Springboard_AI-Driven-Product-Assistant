from pydantic import BaseModel, Field, field_validator, model_validator

from app.schemas.theme_extraction import FeedbackItem


class PainPointExtractionRequest(BaseModel):
    """Input containing multiple customer feedback records."""

    feedback: list[FeedbackItem] = Field(
        min_length=1,
        max_length=500,
    )

    @model_validator(mode="after")
    def validate_unique_ids(self):
        ids = [item.id for item in self.feedback]

        if len(ids) != len(set(ids)):
            raise ValueError("Feedback IDs must be unique.")

        return self


class IdentifiedPainPoint(BaseModel):
    """A customer pain point identified by the agent."""

    name: str = Field(min_length=1)
    category: str = Field(min_length=1)
    severity: str
    description: str = Field(min_length=1)
    feedback_ids: list[str] = Field(min_length=1)
    evidence: list[str] = Field(min_length=1)

    @field_validator("severity")
    @classmethod
    def validate_severity(cls, value: str) -> str:
        value = value.strip().capitalize()

        allowed_values = {"Low", "Medium", "High", "Unknown"}

        if value not in allowed_values:
            raise ValueError("Invalid pain point severity.")

        return value


class PainPointExtractionOutput(BaseModel):
    """Structured output generated by Agent 2."""

    pain_points: list[IdentifiedPainPoint]


class PainPointExtractionResult(BaseModel):
    """Final result returned by Agent 2."""

    total_feedback_analyzed: int = Field(ge=1)
    pain_points: list[IdentifiedPainPoint]