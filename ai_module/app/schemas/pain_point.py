
"""
Pydantic schemas for the Pain Point Identification Agent.

Agent 2 consumes:
- Original customer feedback
- Theme context from Agent 1

Agent 2 produces:
- Identified customer pain points
- Non-pain feedback IDs
- Uncertain feedback IDs
- Independent feature-request candidate IDs

Feature-request classification is independent and may overlap
with pain-point, non-pain, or uncertain classifications.
"""

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
    model_validator,
)

from app.schemas.theme_extraction import (
    FeedbackItem,
    ExtractedTheme,
)


# ---------------------------------------------------------
# AGENT 2 REQUEST
# ---------------------------------------------------------


class PainPointExtractionRequest(BaseModel):
    """Input containing feedback and themes from Agent 1."""

    model_config = ConfigDict(extra="forbid")

    feedback: list[FeedbackItem] = Field(
        ...,
        min_length=1,
        max_length=500,
    )

    theme_context: list[ExtractedTheme] = Field(
        default_factory=list,
        description="Themes produced by Agent 1.",
    )

    @model_validator(mode="after")
    def validate_request(self):
        """Validate feedback IDs and upstream theme references."""

        ids = [
            item.id
            for item in self.feedback
        ]

        if len(ids) != len(set(ids)):
            raise ValueError(
                "Feedback IDs must be unique."
            )

        valid_ids = set(ids)

        for theme in self.theme_context:

            unknown_ids = (
                set(theme.feedback_ids) - valid_ids
            )

            if unknown_ids:
                raise ValueError(
                    "Theme context contains unknown feedback IDs: "
                    f"{sorted(unknown_ids)}"
                )

        return self


# ---------------------------------------------------------
# IDENTIFIED PAIN POINT
# ---------------------------------------------------------


class IdentifiedPainPoint(BaseModel):
    """A customer pain point identified by Agent 2."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(
        ...,
        min_length=1,
    )

    category: str = Field(
        ...,
        min_length=1,
    )

    severity: str = Field(
        ...,
    )

    description: str = Field(
        ...,
        min_length=1,
    )

    feedback_ids: list[str] = Field(
        ...,
        min_length=1,
    )

    evidence: list[str] = Field(
        ...,
        min_length=1,
    )

    @field_validator("severity")
    @classmethod
    def validate_severity(cls, value: str) -> str:
        value = value.strip().capitalize()

        allowed_values = {
            "Low",
            "Medium",
            "High",
            "Unknown",
        }

        if value not in allowed_values:
            raise ValueError(
                "Invalid pain point severity."
            )

        return value

    @field_validator("feedback_ids")
    @classmethod
    def validate_feedback_ids(
        cls,
        values: list[str],
    ) -> list[str]:

        cleaned = [
            value.strip()
            for value in values
        ]

        if any(not value for value in cleaned):
            raise ValueError(
                "Pain-point feedback IDs cannot be empty."
            )

        if len(cleaned) != len(set(cleaned)):
            raise ValueError(
                "Duplicate feedback IDs inside a pain point."
            )

        return cleaned


# ---------------------------------------------------------
# AGENT 2 STRUCTURED OUTPUT
# ---------------------------------------------------------


class PainPointExtractionOutput(BaseModel):
    """Structured output generated by Gemini."""

    model_config = ConfigDict(extra="forbid")

    pain_points: list[IdentifiedPainPoint] = Field(
        default_factory=list,
    )

    non_pain_feedback_ids: list[str] = Field(
        default_factory=list,
        description=(
            "IDs containing praise, neutral statements, "
            "or feedback without an actual problem."
        ),
    )

    uncertain_feedback_ids: list[str] = Field(
        default_factory=list,
        description=(
            "IDs that cannot be classified confidently "
            "and require manual review."
        ),
    )

    feature_request_feedback_ids: list[str] = Field(
        default_factory=list,
        description=(
            "IDs expressing requests for new features, "
            "integrations, improvements, or capabilities. "
            "This is an independent classification and may "
            "overlap with other classification groups."
        ),
    )

    @field_validator(
        "non_pain_feedback_ids",
        "uncertain_feedback_ids",
        "feature_request_feedback_ids",
    )
    @classmethod
    def validate_feedback_id_lists(
        cls,
        values: list[str],
    ) -> list[str]:

        cleaned = [
            value.strip()
            for value in values
        ]

        if any(not value for value in cleaned):
            raise ValueError(
                "Feedback IDs cannot be empty."
            )

        if len(cleaned) != len(set(cleaned)):
            raise ValueError(
                "Duplicate feedback IDs are not allowed."
            )

        return cleaned


# ---------------------------------------------------------
# FINAL AGENT 2 RESULT
# ---------------------------------------------------------


class PainPointExtractionResult(BaseModel):
    """Final validated result returned by Agent 2."""

    model_config = ConfigDict(extra="forbid")

    total_feedback_analyzed: int = Field(
        ...,
        ge=1,
    )

    pain_points: list[IdentifiedPainPoint] = Field(
        default_factory=list,
    )

    non_pain_feedback_ids: list[str] = Field(
        default_factory=list,
    )

    # Canonical name used by the current orchestrator.
    uncertain_feedback_ids: list[str] = Field(
        default_factory=list,
    )

    # Backward-compatible name used by earlier Agent 2 service code.
    unclassified_feedback_ids: list[str] = Field(
        default_factory=list,
    )

    # Independent classification used to select Agent 3 candidates.
    feature_request_feedback_ids: list[str] = Field(
        default_factory=list,
    )

    @model_validator(mode="after")
    def synchronize_uncertain_ids(self):
        """
        Keep uncertain_feedback_ids and unclassified_feedback_ids
        synchronized for compatibility with existing service code.
        """

        combined = list(
            dict.fromkeys(
                self.uncertain_feedback_ids
                + self.unclassified_feedback_ids
            )
        )

        self.uncertain_feedback_ids = combined
        self.unclassified_feedback_ids = combined.copy()

        return self

    @field_validator(
        "non_pain_feedback_ids",
        "uncertain_feedback_ids",
        "unclassified_feedback_ids",
        "feature_request_feedback_ids",
    )
    @classmethod
    def validate_result_id_lists(
        cls,
        values: list[str],
    ) -> list[str]:

        cleaned = [
            value.strip()
            for value in values
        ]

        if any(not value for value in cleaned):
            raise ValueError(
                "Feedback IDs cannot be empty."
            )

        if len(cleaned) != len(set(cleaned)):
            raise ValueError(
                "Duplicate feedback IDs are not allowed."
            )

        return cleaned
