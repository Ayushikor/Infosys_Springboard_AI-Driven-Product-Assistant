
"""
Schemas for the unified Product Assistant chatbot.

The chatbot coordinates:
1. PRD Generation Agent
2. User Story and Acceptance Criteria Agent
3. Feature Prioritization Agent

It can also use outputs from the existing feedback analysis pipeline:
1. Theme Extraction
2. Pain Point Identification
3. Feature Clustering
4. Trend Analysis

The chatbot additionally receives user-scoped database context
from the main backend. This context is retrieved using the
authenticated user's session and serves as the primary source
of factual product information.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any
from uuid import uuid4

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
)


# =========================================================
# CHAT INTENT
# =========================================================

class ChatIntent(str, Enum):
    AUTO = "auto"
    GENERAL = "general"
    PRD_GENERATION = "prd_generation"
    USER_STORY_GENERATION = "user_story_generation"
    FEATURE_PRIORITIZATION = "feature_prioritization"


# =========================================================
# AGENT IDENTIFICATION
# =========================================================

class ProductAgent(str, Enum):
    GENERAL_ASSISTANT = "general_assistant"
    PRD_GENERATION = "prd_generation_agent"
    USER_STORY_GENERATION = "user_story_agent"
    FEATURE_PRIORITIZATION = "feature_prioritization_agent"


# =========================================================
# CHAT MESSAGE
# =========================================================

class ChatMessage(BaseModel):
    model_config = ConfigDict(extra="forbid")

    role: str = Field(
        ...,
        description="Message role: user or assistant.",
    )

    content: str = Field(
        ...,
        min_length=1,
        description="Text content of the conversation message.",
    )

    timestamp: datetime | None = None

    @field_validator("role")
    @classmethod
    def validate_role(cls, value: str) -> str:
        normalized = value.strip().lower()

        if normalized not in {"user", "assistant"}:
            raise ValueError(
                "Message role must be either 'user' or 'assistant'."
            )

        return normalized

    @field_validator("content")
    @classmethod
    def validate_content(cls, value: str) -> str:
        value = value.strip()

        if not value:
            raise ValueError("Message content cannot be empty.")

        return value


# =========================================================
# EXISTING FEEDBACK ANALYSIS CONTEXT
# =========================================================

class ChatAnalysisContext(BaseModel):
    """
    Context generated by the existing four-agent pipeline.

    These fields accept serialized agent outputs so the chatbot
    can use existing analysis without rerunning the pipeline.
    """

    model_config = ConfigDict(extra="allow")

    feedback: list[dict[str, Any]] = Field(
        default_factory=list
    )

    themes: list[dict[str, Any]] = Field(
        default_factory=list
    )

    pain_points: list[dict[str, Any]] = Field(
        default_factory=list
    )

    feature_clusters: list[dict[str, Any]] = Field(
        default_factory=list
    )

    trends: list[dict[str, Any]] = Field(
        default_factory=list
    )


# =========================================================
# GENERATED AGENT CONTEXT
# =========================================================

class GeneratedArtifactContext(BaseModel):
    """
    Stores outputs generated during the current conversation.

    These outputs allow downstream agents to use earlier
    generated artifacts.
    """

    model_config = ConfigDict(extra="allow")

    prd: dict[str, Any] | None = None

    user_stories: dict[str, Any] | None = None

    feature_prioritization: dict[str, Any] | None = None


# =========================================================
# CHAT REQUEST
# =========================================================

class ChatRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    conversation_id: str | None = Field(
        default=None,
        description="Existing conversation ID, if available.",
    )

    product_name: str = Field(
        ...,
        min_length=2,
        description="Name of the product being discussed.",
    )

    product_context: str | None = Field(
        default=None,
        description="Additional product information.",
    )

    message: str = Field(
        ...,
        min_length=1,
        description="Latest user message.",
    )

    intent: ChatIntent = Field(
        default=ChatIntent.AUTO,
        description="Requested agent action or automatic routing.",
    )

    conversation_history: list[ChatMessage] = Field(
        default_factory=list,
        description="Previous messages in the conversation.",
    )

    analysis_context: ChatAnalysisContext = Field(
        default_factory=ChatAnalysisContext,
        description="Outputs from the existing four-agent analysis pipeline.",
    )

    generated_artifacts: GeneratedArtifactContext = Field(
        default_factory=GeneratedArtifactContext,
        description="Previously generated PRDs, user stories, and priorities.",
    )

    # -----------------------------------------------------
    # MONGODB DATABASE CONTEXT
    # -----------------------------------------------------

    database_context: dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "User-scoped MongoDB data retrieved by the authenticated "
            "main backend. Includes product records, feedback, themes, "
            "features, PRDs, roadmap, activity, analysis runs, analysis "
            "batches, workspace information, and data inventory. "
            "This context is the primary source of factual information "
            "for chatbot responses."
        ),
    )

    @field_validator("message")
    @classmethod
    def validate_message(cls, value: str) -> str:
        value = value.strip()

        if not value:
            raise ValueError("Chat message cannot be empty.")

        return value

    @field_validator("product_name")
    @classmethod
    def validate_product_name(cls, value: str) -> str:
        value = value.strip()

        if not value:
            raise ValueError("Product name cannot be empty.")

        return value

    @field_validator("conversation_id")
    @classmethod
    def validate_conversation_id(
        cls,
        value: str | None,
    ) -> str | None:
        if value is not None:
            value = value.strip()

            if not value:
                raise ValueError(
                    "Conversation ID cannot be empty."
                )

        return value


# =========================================================
# AGENT EXECUTION STATUS
# =========================================================

class AgentExecutionStatus(str, Enum):
    COMPLETED = "completed"
    FAILED = "failed"
    NOT_REQUIRED = "not_required"


# =========================================================
# AGENT EXECUTION DETAILS
# =========================================================

class AgentExecution(BaseModel):
    model_config = ConfigDict(extra="forbid")

    agent: ProductAgent

    status: AgentExecutionStatus

    description: str | None = None


# =========================================================
# CHAT RESPONSE
# =========================================================

class ChatResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    success: bool = True

    conversation_id: str

    product_name: str

    user_message: str

    assistant_message: str

    intent: ChatIntent

    agent_used: ProductAgent

    agent_execution: list[AgentExecution] = Field(
        default_factory=list
    )

    artifact_type: str | None = None

    artifact: dict[str, Any] | None = None

    requires_more_information: bool = False

    suggested_next_action: str | None = None

    generated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )


# =========================================================
# CHAT RESPONSE BUILDER
# =========================================================

def build_chat_response(
    *,
    product_name: str,
    user_message: str,
    assistant_message: str,
    intent: ChatIntent,
    agent_used: ProductAgent,
    conversation_id: str | None = None,
    agent_execution: list[AgentExecution] | None = None,
    artifact_type: str | None = None,
    artifact: dict[str, Any] | None = None,
    requires_more_information: bool = False,
    suggested_next_action: str | None = None,
) -> ChatResponse:

    return ChatResponse(
        success=True,
        conversation_id=conversation_id or str(uuid4()),
        product_name=product_name,
        user_message=user_message,
        assistant_message=assistant_message,
        intent=intent,
        agent_used=agent_used,
        agent_execution=agent_execution or [],
        artifact_type=artifact_type,
        artifact=artifact,
        requires_more_information=requires_more_information,
        suggested_next_action=suggested_next_action,
        generated_at=datetime.now(timezone.utc),
    )
