"""
Pydantic schemas for the User Story and Acceptance Criteria Agent.

Agent consumes:
- Generated PRD from the PRD Generation Agent
- Product requirements
- Target users
- Feature scope and objectives

Agent produces:
- Structured user stories
- Acceptance criteria in Given-When-Then format
- Story dependencies
- Validation scenarios
"""

from typing import Literal

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
    model_validator,
)

from app.schemas.prd import PRDGenerationOutput


# ---------------------------------------------------------
# ACCEPTANCE CRITERION
# ---------------------------------------------------------


class AcceptanceCriterion(BaseModel):
    """One acceptance criterion written in Given-When-Then format."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    criterion_id: str = Field(..., min_length=1)

    given: str = Field(
        ...,
        min_length=1,
        description="Initial condition or context.",
    )

    when: str = Field(
        ...,
        min_length=1,
        description="Action performed by the user or system.",
    )

    then: str = Field(
        ...,
        min_length=1,
        description="Expected observable outcome.",
    )

    @field_validator("criterion_id", "given", "when", "then")
    @classmethod
    def validate_text(cls, value: str) -> str:
        value = value.strip()

        if not value:
            raise ValueError("This field cannot be empty.")

        return value


# ---------------------------------------------------------
# USER STORY
# ---------------------------------------------------------


class UserStory(BaseModel):
    """One user story derived from a PRD requirement."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    story_id: str = Field(
        ...,
        min_length=1,
        description="Unique user story identifier.",
    )

    title: str = Field(
        ...,
        min_length=1,
    )

    user_type: str = Field(
        ...,
        min_length=1,
        description="User role represented by the story.",
    )

    user_story: str = Field(
        ...,
        min_length=1,
        description=(
            "As a [user], I want [capability], "
            "so that [benefit]."
        ),
    )

    requirement_ids: list[str] = Field(
        ...,
        min_length=1,
        description="PRD functional requirement IDs addressed by this story.",
    )

    priority: Literal[
        "Must Have",
        "Should Have",
        "Could Have",
        "Won't Have",
    ] = Field(
        ...,
        description="Priority inherited from the related PRD requirements.",
    )

    acceptance_criteria: list[AcceptanceCriterion] = Field(
        ...,
        min_length=1,
    )

    dependencies: list[str] = Field(
        default_factory=list,
        description="Other story IDs that must be completed first.",
    )

    notes: list[str] = Field(
        default_factory=list,
        description="Additional implementation or clarification notes.",
    )

    @field_validator(
        "requirement_ids",
        "dependencies",
        "notes",
    )
    @classmethod
    def clean_string_lists(
        cls,
        values: list[str],
    ) -> list[str]:
        cleaned = [value.strip() for value in values]

        if any(not value for value in cleaned):
            raise ValueError("List entries cannot be empty.")

        return list(dict.fromkeys(cleaned))

    @model_validator(mode="after")
    def validate_acceptance_criteria(self):
        criterion_ids = [
            criterion.criterion_id
            for criterion in self.acceptance_criteria
        ]

        if len(criterion_ids) != len(set(criterion_ids)):
            raise ValueError(
                "Acceptance criterion IDs must be unique within a story."
            )

        if self.story_id in self.dependencies:
            raise ValueError(
                "A user story cannot depend on itself."
            )

        return self


# ---------------------------------------------------------
# USER STORY GENERATION REQUEST
# ---------------------------------------------------------


class UserStoryGenerationRequest(BaseModel):
    """
    Input supplied to the User Story Agent.

    The generated PRD is the primary source for creating
    user stories and acceptance criteria.
    """

    model_config = ConfigDict(extra="forbid")

    product_name: str = Field(
        ...,
        min_length=1,
    )

    prd: PRDGenerationOutput = Field(
        ...,
        description="Validated PRD generated by the PRD Generation Agent.",
    )


# ---------------------------------------------------------
# GEMINI STRUCTURED OUTPUT
# ---------------------------------------------------------


class UserStoryGenerationOutput(BaseModel):
    """Structured draft output generated by Gemini."""

    model_config = ConfigDict(extra="forbid")

    user_stories: list[UserStory] = Field(
        ...,
        min_length=1,
    )

    generation_notes: list[str] = Field(
        default_factory=list,
        description="Observations or limitations during story generation.",
    )

    @model_validator(mode="after")
    def validate_story_assignments(self):
        story_ids = [
            story.story_id
            for story in self.user_stories
        ]

        if len(story_ids) != len(set(story_ids)):
            raise ValueError(
                "User story IDs must be unique."
            )

        known_story_ids = set(story_ids)

        for story in self.user_stories:
            unknown_dependencies = (
                set(story.dependencies) - known_story_ids
            )

            if unknown_dependencies:
                raise ValueError(
                    f"Story '{story.story_id}' references unknown "
                    f"dependencies: {sorted(unknown_dependencies)}"
                )

        return self


# ---------------------------------------------------------
# FINAL USER STORY RESULT
# ---------------------------------------------------------


class UserStoryGenerationResult(BaseModel):
    """Final validated result returned by the User Story Agent."""

    model_config = ConfigDict(extra="forbid")

    product_name: str = Field(
        ...,
        min_length=1,
    )

    prd_title: str = Field(
        ...,
        min_length=1,
    )

    total_user_stories: int = Field(
        ...,
        ge=1,
    )

    total_acceptance_criteria: int = Field(
        ...,
        ge=1,
    )

    user_stories: list[UserStory] = Field(
        ...,
        min_length=1,
    )

    generation_notes: list[str] = Field(
        default_factory=list,
    )

    @model_validator(mode="after")
    def validate_result_counts(self):
        if self.total_user_stories != len(self.user_stories):
            raise ValueError(
                "Total user story count does not match."
            )

        actual_criteria_count = sum(
            len(story.acceptance_criteria)
            for story in self.user_stories
        )

        if self.total_acceptance_criteria != actual_criteria_count:
            raise ValueError(
                "Total acceptance criteria count does not match."
            )

        return self


# ---------------------------------------------------------
# BUILD FINAL RESULT
# ---------------------------------------------------------


def build_user_story_result(
    request: UserStoryGenerationRequest,
    output: UserStoryGenerationOutput,
) -> UserStoryGenerationResult:
    """
    Reconcile generated stories against the original PRD.

    Validates:
    - Every requirement reference exists in the PRD.
    - Every story has at least one acceptance criterion.
    - Story IDs are unique.
    - Dependency references are valid.
    - Final counts match the generated data.
    """

    valid_requirement_ids = {
        requirement.requirement_id
        for requirement in request.prd.functional_requirements
    }

    for story in output.user_stories:
        unknown_requirement_ids = (
            set(story.requirement_ids) - valid_requirement_ids
        )

        if unknown_requirement_ids:
            raise ValueError(
                f"Story '{story.story_id}' references unknown "
                f"PRD requirements: {sorted(unknown_requirement_ids)}"
            )

    return UserStoryGenerationResult(
        product_name=request.product_name,
        prd_title=request.prd.title,
        total_user_stories=len(output.user_stories),
        total_acceptance_criteria=sum(
            len(story.acceptance_criteria)
            for story in output.user_stories
        ),
        user_stories=output.user_stories,
        generation_notes=output.generation_notes,
    )